test "representative key codes match the NDK" {
    const std = @import("std");
    try std.testing.expectEqual(@as(i32, -1), KeyCode.unknown.rawValue());
    try std.testing.expectEqual(@as(i32, 2017), KeyCode.a.rawValue());
    try std.testing.expectEqual(@as(i32, 2101), KeyCode.f12.rawValue());
}
